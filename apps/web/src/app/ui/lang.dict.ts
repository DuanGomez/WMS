/** Traduce un fragmento de un texto compuesto con EN o EN_PATTERNS; si no hay traducción lo deja igual. */
function part(s: string): string {
  if (EN[s] != null) return EN[s];
  for (const [re, fn] of EN_PATTERNS) {
    const m = s.match(re);
    if (m) return fn(m);
  }
  return s;
}

