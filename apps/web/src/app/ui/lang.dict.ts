/** Traduce nombres de meses/días y a. m./p. m. generados por Intl en es-CO. */
function dates(s: string): string {
  return s
    .replace(/\s?a\.\s?m\./gi, ' AM')
    .replace(/\s?p\.\s?m\./gi, ' PM')
    .replace(/(\d+) de ([a-záéíóú]+)( de (\d{4}))?/gi, (_m, d, mo, _y, y) => `${W[mo.toLowerCase()] ?? mo} ${d}${y ? ', ' + y : ''}`)
    .replace(/\b(hace|ahora|ayer|hoy)\b/gi, (w) => EN[w.toLowerCase()] ?? w)
    .replace(/[a-záéíóú]+\.?/gi, (w) => {
      const k = w.replace('.', '').toLowerCase();
      return W[k] ?? w;
    });
}
