/** Devuelve el SVG del ícono como texto (para marcadores de Leaflet). */
export function iconSvg(name: string, size = 16, stroke = 2): string {
  const el = createElement(ICONS[name] ?? Circle, {
    width: size,
    height: size,
    'stroke-width': stroke,
  });
  return el.outerHTML;
}

@Component({
  selector: 'app-icon',
  template: '',
  changeDetection: ChangeDetectionStrategy.OnPush,
  host: { 'aria-hidden': 'true', style: 'display:inline-flex;flex:none;line-height:0' },
})
export class IconComponent {
  readonly name = input.required<string>();
  readonly size = input(18);
  readonly stroke = input(1.9);
  private host = inject(ElementRef<HTMLElement>);

  constructor() {
    effect(() => {
      const el = createElement(ICONS[this.name()] ?? Circle, {
        width: this.size(),
        height: this.size(),
        'stroke-width': this.stroke(),
      });
      this.host.nativeElement.replaceChildren(el);
    });
  }
}
